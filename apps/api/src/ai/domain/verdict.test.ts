import { describe, expect, it } from 'vitest';
import { givesVerdict } from './verdict.js';

describe('teacher sentences that judge a guess', () => {
  it.each([
    '对，右盘有3组、每组3根黄瓜；想想一棵青菜相当于几根黄瓜。',
    '对的，就是九根。',
    '对对，就是九根。',
    '对啦！再数一遍。',
    '对呀～再数数。',
    '对哒，九根。',
    '是的！你再数一遍吧。',
    '嗯，对，就是九根。',
    '嗯嗯对，九根',
    '没错，九根。',
    '不对，再数一数。',
    '好像不太对哦，再数数。',
    '不是九哦，再看看右盘。',
    '错了，再想想。',
    '错啦，再想想。',
    '你猜对了，真棒！',
    '你想对了！',
    '你做对了，真棒！',
    '你数错了一组，再数一遍。',
    '你说得对，每组三根。',
    '答案正确。',
    '九根是对的。',
    '六根是错的，再数数。',
    '每组三根，你这样就对了。',
    '你这样数不对，再一组一组地数。',
  ])('refuses %s', (sentence) => {
    expect(givesVerdict(sentence)).toBe(true);
  });
});

describe('ordinary teacher sentences', () => {
  it.each([
    // Replies a real model gave to synthetic questions in the #173 spike and the #178 check.
    '你把三组各三根合起来了，下一步数数一共有几根黄瓜。',
    '看天平旁边的篮子，先找找它在哪里吧。',
    '看天平横梁，两边一样重时它就是平的；想想两棵青菜和六个苹果有什么关系。',
    '请把一棵青菜拖进旁边的篮子，看看天平会怎样变化。',
    '你是想问拿走的苹果放在哪里吗？',
    '你说的“那个”是指什么？请再说清楚一点。',
    '天平不会歪；请接着说说每次换苹果后为什么还能保持平衡。',
    '换最右边还没换的苹果，试着把它换成一组黄瓜。',
    '看看右盘的三组黄瓜，每组三根；数数一共几根，再说说看。',
    '看右盘，每组三根黄瓜，数数一共有几组，再说说答案。',
    '先圈出右盘的每一组黄瓜，再数一数有几组。',
    '你说外面下雨了；请告诉我这道题里青菜和黄瓜的关系。',
    '你卡在哪一点：每个苹果换两根黄瓜，还是三个苹果？',
    '你是没听懂题目，还是想让我再说一遍？',
    '请把右盘三组黄瓜的根数合起来，再自己核对一棵青菜相当于几根。',
    '回想天平变平时另一边的黄瓜，再自己核对有几根。',
    '看看右盘的三个苹果是否都已换成黄瓜，再自己核对天平是否仍平。',
    '我这里看不到图，请问篮子在天平的哪一侧？',
    // The teacher sending the child to check, and words that merely contain 对.
    '数一数，看看对不对。',
    '你说的九对不对，自己数数看。',
    '想想对不对，再说出来。',
    '自己核对一下吧。',
    '对比一下两边的黄瓜。',
    '对着右盘一组一组地数。',
    '数一数对面盘子里的黄瓜。',
    '找对应的那一组黄瓜。',
  ])('keeps %s', (sentence) => {
    expect(givesVerdict(sentence)).toBe(false);
  });
});
